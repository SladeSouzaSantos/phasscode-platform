#!/usr/bin/env python3
"""Read-only HydraDB PPKS shadow reader for a strictly isolated LAB.

NOT a production Orbe adapter; no API/chat integration or DB writes.
The PPKS is canonical. HydraDB output is accepted only if it exactly
matches every expected claim/source row of the selected public-PPKS fixture.
Any unavailable/incomplete/extra/malformed result falls back to PPKS.
"""
from __future__ import annotations

import argparse
from collections import Counter
import json
import os
from pathlib import Path
import re
import runpy
import sys
from typing import Callable
from urllib.request import ProxyHandler, build_opener

ROOT = Path.home() / "hydradb-lab"
REPO = ROOT / "phasscode-platform"
BENCH = ROOT / "benchmarks"
STAGE = runpy.run_path(
    str(REPO / "scripts/hydradb-neo4j-ppks-evidence-contract.py")
)
CORE = STAGE["CORE"]
FIND_QUERY = (
    "MATCH (s:Skill)<-[:USES_TECHNOLOGY]-(c:Claim)"
    "-[:SUPPORTED_BY]->(src:Source) "
    "WHERE s.normalized_name = $skill AND s.lab_run = $run "
    "RETURN c.record_key AS record, c.scope AS scope, "
    "src.source_key AS source, src.verification AS verification, "
    "src.origin AS origin ORDER BY record, source"
)
SOURCE_QUERY = (
    "MATCH (src:Source) WHERE src.source_key = $source "
    "AND src.lab_run = $run "
    "RETURN src.source_key AS source, "
    "src.verification AS verification, src.origin AS origin LIMIT 1"
)
FIND_COLUMNS = ["record", "scope", "source", "verification", "origin"]
SOURCE_COLUMNS = ["source", "verification", "origin"]
EXPECTED_COUNTS = {
    "records": 7, "skills": 10, "claims": 14,
    "sources": 16, "vertices": 47, "edges": 60,
}
QUERY = Callable[[str, dict], dict]


def ensure(condition: bool, code: str) -> None:
    if not condition:
        raise ValueError(code)


def report_run(path: Path) -> str:
    """Only reports generated by a successful stage-three LAB run qualify."""
    ensure(not path.is_symlink(), "SHADOW_REPORT_SYMLINK_FORBIDDEN")
    actual = path.resolve(strict=True)
    ensure(actual.parent == BENCH.resolve(strict=True), "SHADOW_REPORT_OUTSIDE_LAB")
    ensure(
        bool(re.fullmatch(r"ppks-contract-\d{8}T\d{6}Z\.json", actual.name)),
        "SHADOW_REPORT_NAME_INVALID"
    )
    stat = actual.stat()
    ensure(stat.st_uid == os.getuid(), "SHADOW_REPORT_OWNER_INVALID")
    ensure((stat.st_mode & 0o077) == 0, "SHADOW_REPORT_NOT_PRIVATE")
    ensure(0 < stat.st_size < 200_000, "SHADOW_REPORT_SIZE_INVALID")
    data = json.loads(actual.read_text(encoding="utf-8"))
    ensure(data.get("scenario") == "ppks_claim_specific_source_contract",
           "SHADOW_REPORT_SCENARIO_INVALID")
    ensure(data.get("counts") == EXPECTED_COUNTS, "SHADOW_REPORT_COUNTS_INVALID")
    ensure(
        data.get("parity") ==
        "PASS: parameterized claim-source retrieval in both LAB engines",
        "SHADOW_REPORT_NOT_APPROVED"
    )
    key = data.get("lab_run")
    ensure(isinstance(key, str) and bool(re.fullmatch(r"[0-9]{10,20}", key)),
           "SHADOW_REPORT_RUN_INVALID")
    return key


def canonical_find(records: list[dict], skill: str) -> tuple[list[dict], list[tuple]]:
    groups = []
    rows = []
    for record in records:
        for claim in record["claims"]:
            if claim["skill"].casefold() != skill.casefold():
                continue
            sources = [record["sources"][key] for key in claim["source_keys"]]
            groups.append({
                "record": record["key"], "skill": claim["skill"],
                "scope": record["scope"],
                "sourceIds": list(claim["source_keys"]),
                "sources": [
                    {"id": src["source_key"],
                     "verification": src["verification"],
                     "origin": src["origin"]}
                    for src in sources
                ],
            })
            for src in sources:
                rows.append((
                    record["key"], record["scope"], src["source_key"],
                    src["verification"], src["origin"]
                ))
    groups.sort(key=lambda group: (group["record"], group["skill"]))
    return groups, sorted(rows)


def canonical_source(records: list[dict], key: str) -> tuple[dict | None, list[tuple]]:
    for record in records:
        if key in record["sources"]:
            src = record["sources"][key]
            return (
                {"id": key, "verification": src["verification"],
                 "origin": src["origin"], "visibility": src["visibility"]},
                [(key, src["verification"], src["origin"])],
            )
    return None, []


class ShadowReader:
    """Passive experimental reader that returns only canonical PPKS payloads."""

    def __init__(
        self, records: list[dict], run_key: str | None = None,
        query: QUERY | None = None,
    ):
        self.records = records
        self.run_key = run_key
        self.query = query
        ensure((run_key is None) == (query is None),
               "SHADOW_READER_MODE_INCONSISTENT")
        if run_key is not None:
            ensure(bool(re.fullmatch(r"[0-9]{10,20}", run_key)),
                   "SHADOW_INVALID_RUN_KEY")

    def _verified(
        self, query: str, params: dict, columns: list[str], expected: list[tuple],
    ) -> tuple[str, str]:
        if self.query is None:
            return "canonical", "GRAPH_MODE_OFF"
        # The canonical payload is returned even when graph parity succeeds;
        # the graph is used for passive verification, not as the source of truth.
        try:
            ensure("$run" in query and params.get("run") == self.run_key,
                   "SHADOW_UNSCOPED_READ_BLOCKED")
            response = self.query(query, params)
            ensure(response.get("columns") == columns,
                   "GRAPH_COLUMNS_INVALID")
            got = STAGE["READ_ROWS"]("hydradb", response)
            ensure(Counter(got) == Counter(expected),
                   "GRAPH_MISMATCH_WITH_PPKS")
            return "graph_verified", "MATCHED_CANONICAL_PPKS"
        except Exception:
            # No credentials, query text, response bodies or user data in logs.
            return "canonical_fallback", "GRAPH_UNAVAILABLE_OR_MISMATCH"

    def find_evidence(self, skill: str, limit: int = 5) -> dict:
        ensure(isinstance(skill, str) and 0 < len(skill) <= 90,
               "SHADOW_INVALID_SKILL")
        ensure(isinstance(limit, int) and not isinstance(limit, bool)
               and 1 <= limit <= 20, "SHADOW_INVALID_CLAIM_LIMIT")
        groups, expected = canonical_find(self.records, skill)
        state, reason = self._verified(
            FIND_QUERY, {"skill": skill.casefold(), "run": self.run_key},
            FIND_COLUMNS, expected,
        )
        # Apply claim limit AFTER complete provenance verification. Limiting
        # source rows would silently omit valid sources of a selected claim.
        selected = groups[:limit]
        return {
            "skill": skill, "status": state, "reason": reason,
            "claims": selected, "sourceCount": sum(
                len(group["sourceIds"]) for group in selected
            ),
        }

    def get_source(self, key: str) -> dict:
        ensure(isinstance(key, str) and 0 < len(key) <= 140,
               "SHADOW_INVALID_SOURCE_KEY")
        source, expected = canonical_source(self.records, key)
        state, reason = self._verified(
            SOURCE_QUERY, {"source": key, "run": self.run_key},
            SOURCE_COLUMNS, expected,
        )
        return {
            "sourceKey": key, "status": state, "reason": reason,
            "source": source,
        }


def hydra_transport(token: str) -> QUERY:
    opener = build_opener(ProxyHandler({}))
    def query(cypher: str, params: dict) -> dict:
        return STAGE["paired_query"](
            opener, "hydradb", cypher, params, token, ""
        )
    return query


def probe(reader: ShadowReader, require_graph: bool) -> bool:
    outcomes: list[tuple[str, str, str, int]] = []
    for name in ("Java", "Flutter", "TypeScript", "Node.js", "Go"):
        result = reader.find_evidence(name, limit=20)
        outcomes.append(("skill", name, result["status"], len(result["claims"])))
    # The code-reviewed and catalog-only sources MUST remain distinct.
    for key in (
        "phasscode-platform--ports",
        "phasscode-platform--catalog",
        "experiencia-sig--catalog",
        "web-portfolio-v2--tests",
        "missing-source-key",
    ):
        result = reader.get_source(key)
        outcomes.append((
            "source", key, result["status"],
            int(result["source"] is not None),
        ))
    for kind, name, status, count in outcomes:
        print("SHADOW_PROBE", kind, name, status, "RESULTS", count)
    if require_graph and any(status != "graph_verified"
                             for _, _, status, _ in outcomes):
        print("SHADOW_PROBE_GRAPH_VERIFICATION_FAILED")
        return False
    print("SHADOW_PROBE_CANONICAL_SAFE")
    return True


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--mode", choices=("off", "shadow"), default="off")
    parser.add_argument("--report", type=Path,
                        help="Private ppks-contract JSON report from LAB")
    parser.add_argument("--probe", action="store_true",
                        help="Run ten safe read-only questions, no writes")
    parser.add_argument("--skill", help="One public technology lookup")
    parser.add_argument("--source", help="One PPKS public source key")
    parser.add_argument("--limit", type=int, default=5)
    parser.add_argument("--require-graph", action="store_true",
                        help="Fail the validation if any query used fallback")
    args = parser.parse_args()
    ensure(args.probe or bool(args.skill) or bool(args.source),
           "SHADOW_CHOOSE_PROBE_SKILL_OR_SOURCE")
    if args.require_graph:
        ensure(args.mode == "shadow", "SHADOW_REQUIRE_GRAPH_NEEDS_SHADOW_MODE")
    env = CORE["check_lab"]()
    ensure(env.get("ORBE_GRAPHRAG_MODE") == "off",
           "SHADOW_ORBE_LAB_GRAPH_MODE_MUST_BE_OFF")
    records = STAGE["data_fixture"]()
    if args.mode == "off":
        ensure(args.report is None, "SHADOW_OFF_DOES_NOT_USE_GRAPH_REPORT")
        reader = ShadowReader(records)
    else:
        ensure(args.report is not None, "SHADOW_REPORT_REQUIRED")
        key = report_run(args.report)
        token = (ROOT / "secrets" / "hydradb_auth_token").read_text(
            encoding="utf-8"
        ).strip()
        ensure(len(token) >= 32, "SHADOW_HYDRADB_TOKEN_MISSING")
        reader = ShadowReader(records, key, hydra_transport(token))

    if args.probe:
        if not probe(reader, args.require_graph):
            sys.exit(1)
    if args.skill:
        result = reader.find_evidence(args.skill, args.limit)
        print("SHADOW_EVIDENCE", json.dumps(
            result, ensure_ascii=False, separators=(",", ":")
        ))
        if args.require_graph and result["status"] != "graph_verified":
            sys.exit(1)
    if args.source:
        result = reader.get_source(args.source)
        print("SHADOW_SOURCE", json.dumps(
            result, ensure_ascii=False, separators=(",", ":")
        ))
        if args.require_graph and result["status"] != "graph_verified":
            sys.exit(1)


if __name__ == "__main__":
    try:
        main()
    except (ValueError, OSError, TypeError, json.JSONDecodeError) as error:
        # Restricted to validation codes, no credential or HTTP payload echo.
        print("SHADOW_READER_ERROR", type(error).__name__,
              str(error) if isinstance(error, ValueError)
              else "INVALID_LAB_STATE", file=sys.stderr)
        sys.exit(1)
